import type { Metadata } from "next";
import { notFound } from "next/navigation";
import { Breadcrumbs, Prose, Section } from "@/components/ui/Card";
import { GameFacts, GameStage, GameTile, GameTilesRow, gameHref } from "@/components/casino/Games";
import { getGame, getGames, getProviders } from "@/lib/data";

export async function generateStaticParams() {
  const games = await getGames({ kind: ["mybet", "crash"] });
  return games.map(g => ({ game: g.slug }));
}

export async function generateMetadata(props: PageProps<"/allgamesentrance/[game]">): Promise<Metadata> {
  const { game } = await props.params;
  const g = await getGame(game);
  return g ? { title: `${g.name} – Mybet Games`, description: `Play ${g.name} on Mybet.${g.rtp ? ` RTP ${g.rtp}%.` : ""}` } : {};
}

export default async function GamePage(props: PageProps<"/allgamesentrance/[game]">) {
  const { game: slug } = await props.params;
  const [game, providers, all] = await Promise.all([getGame(slug), getProviders(), getGames({ kind: ["mybet", "crash"] })]);
  if (!game || (game.kind !== "mybet" && game.kind !== "crash")) notFound();
  const provider = providers.find(p => p.slug === game.provider);
  const similar = all.filter(g => g.slug !== game.slug && g.tags.some(t => game.tags.includes(t))).slice(0, 7);

  return (
    <>
      <Breadcrumbs items={[{ label: "Mybet Games", href: "/allgamesentrance" }, { label: game.name }]} />
      <GameStage game={game} providerName={provider?.name} />
      <div className="grid grid-cols-1 gap-2 xl:grid-cols-2">
        <Section title="How to play" id="rules">
          <Prose sections={[
            { heading: "Rules", paragraphs: [
              `Choose your stake and start a round of ${game.name}. Results are generated by a certified random number generator.`,
              "Winnings are credited to your balance as soon as the round ends.",
            ] },
            { heading: "Fair play", paragraphs: ["Every round can be verified in your bet history. If a connection drops, the round is settled automatically."] },
          ]} />
        </Section>
        <GameFacts game={game} providerName={provider?.name} />
      </div>
      {similar.length ? (
        <Section title="Similar games">
          <GameTilesRow>{similar.map(g => <GameTile key={g.slug} game={g} href={gameHref(g)} />)}</GameTilesRow>
        </Section>
      ) : null}
    </>
  );
}
